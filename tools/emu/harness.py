"""Differential-test harness: run a function of the original on random memory state and emit a
Rust test that replays the same state against the port and compares the resulting memory.

    h = Harness('golden_tech_system')
    h.case(writes=[(addr, bytes), ...], call=lambda e: e.call(0x4eb5e0, this=THIS),
           rust='tech_system::value(&m, THIS)', watch=[(THIS, 0x34)], ret=True)
    h.save()
"""
import os
import random
import struct
import sys

sys.path.insert(0, os.path.dirname(__file__))
from emu import Emu, OBJ_BASE, HEAP_BASE  # noqa: E402

TESTS = os.path.join(os.path.dirname(__file__), '..', '..', 'crates', 'ht2-sim', 'tests')
CLOCK_OBJ = OBJ_BASE + 0x100000
ZERO_LEN = 0x100000


def f32(x):
    return struct.unpack('<f', struct.pack('<f', x))[0]


def pack(kind, v):
    fmt = {'f': '<f', 'i': '<i', 'h': '<h', 'u': '<I', 'd': '<d', 'b': '<B'}[kind]
    if kind == 'u':
        v &= 0xffffffff
    return struct.pack(fmt, v)


def rs_f32(x):
    if x != x:
        return 'f32::NAN'
    if x in (float('inf'), float('-inf')):
        return 'f32::INFINITY' if x > 0 else 'f32::NEG_INFINITY'
    return repr(float(f32(x))) + 'f32'


class Harness:
    def __init__(self, name, header_uses):
        self.name = name
        self.uses = header_uses
        self.e = Emu()
        self.e.install_crt_hooks()
        self.e.load_tech()
        self.cases = []
        self.rnd = random.Random(0xC0FFEE)

    def reset(self, time=0.0, dt=0.016):
        e = self.e
        e.write(OBJ_BASE, bytes(ZERO_LEN))
        e.write(HEAP_BASE, bytes(0x100000))
        e.heap_next = HEAP_BASE
        e.write(0x6974c4, struct.pack('<I', CLOCK_OBJ))
        e.write(0x6974c2, b'\0\0')
        e.write(CLOCK_OBJ + 0xb98, struct.pack('<d', time))
        e.write(CLOCK_OBJ + 0xb90, struct.pack('<d', dt))

    def case(self, writes, call, rust, watch, ret=None, time=0.0, dt=0.016, setup_rust='', prepare=None, ret_int=False):
        """`writes`: initial memory. `call(emu)` runs the original and returns ST0.
        `rust` is a Rust expression/statement block evaluated with `m` in scope, returning f32 if `ret`."""
        e = self.e
        self.reset(time, dt)
        init = []
        for addr, data in writes:
            e.write(addr, data)
            init.append((addr, data))
        if prepare:
            prepare(e)   # e.g. run original constructors; mirror them in `setup_rust`
        dynamic = callable(watch)
        before = [] if dynamic else [(b, e.read(b, n)) for b, n in watch]
        r = call(e)
        if dynamic:                       # regions known only after the original ran (heap objects)
            watch = watch(e)
            before = [(b, bytes(n)) for b, n in watch]
        if callable(setup_rust):
            setup_rust = setup_rust(e)
        if ret_int:
            r = e.eax
        after = [(b, e.read(b, n)) for b, n in watch]
        diffs = []
        for (b, old), (_, new) in zip(before, after):
            i = 0
            while i < len(old):
                if old[i] != new[i]:
                    j = i
                    while j < len(old) and (old[j] != new[j] or (j + 1 < len(old) and old[j + 1] != new[j + 1])):
                        j += 1
                    diffs.append((b + i, new[i:j]))
                    i = j
                else:
                    i += 1
        self.cases.append(dict(writes=init, rust=rust, watch=watch, ret=r if ret else None, ret_int=ret_int, diffs=diffs,
                               time=time, dt=dt, setup=setup_rust))

    def save(self):
        out = ['// Generated by tools/emu/ from the original code running in an emulator; do not edit.',
               '#![allow(unused_imports, unused_variables, unused_mut)]',
               'use ht2_sim::*;', *self.uses, '',
               'fn close(got: f32, want: f32) -> bool {',
               '    if want.is_nan() { return got.is_nan(); }',
               '    (got - want).abs() <= 1e-4 * want.abs().max(1.0)',
               '}', '',
               '/// Equal, except that floats of ordinary magnitude may differ by x87-versus-f64 rounding noise',
               '/// (about 1e-6 relative); integers, pointers and zeros must match exactly.',
               'fn mem_close(got: &[u8], want: &[u8]) -> bool {',
               '    if got.len() != want.len() { return false; }',
               '    got.chunks(4).zip(want.chunks(4)).all(|(a, b)| {',
               '        if a == b { return true; }',
               '        if a.len() != 4 { return false; }',
               '        let noise = |i: u32| { let e = (i >> 23) & 0xff; (86..127).contains(&e) };',
               '        let (ni, mi) = (u32::from_le_bytes(a.try_into().unwrap()), u32::from_le_bytes(b.try_into().unwrap()));',
               '        if noise(ni) && noise(mi) && (f32::from_le_bytes(a.try_into().unwrap()) - f32::from_le_bytes(b.try_into().unwrap())).abs() <= 1e-6 { return true; }',
               '        let (x, y) = (f32::from_le_bytes(a.try_into().unwrap()), f32::from_le_bytes(b.try_into().unwrap()));',
               '        let ordinary = |v: f32| v.is_finite() && (v == 0.0 || (v.abs() > 1e-7 && v.abs() < 1e7));',
               '        let (xi, yi) = (u32::from_le_bytes(a.try_into().unwrap()), u32::from_le_bytes(b.try_into().unwrap()));',
               '        let tiny = |i: u32| ((i >> 23) & 0xff) < 100;   // looks like an integer or a pointer, not a float',
               '        !tiny(xi) && !tiny(yi) && ordinary(x) && ordinary(y) && (x - y).abs() <= 2e-5 * x.abs().max(y.abs()).max(1.0)',
               '    })',
               '}', '',
               'fn report(base: u32, got: &[u8], want: &[u8]) -> String {',
               '    let mut out = String::new();',
               '    for (i, (a, b)) in got.chunks(4).zip(want.chunks(4)).enumerate() {',
               '        if a != b && out.len() < 600 {',
               '            let f = |x: &[u8]| if x.len() == 4 { format!("{:#010x}/{}", u32::from_le_bytes(x.try_into().unwrap()), f32::from_le_bytes(x.try_into().unwrap())) } else { format!("{x:?}") };',
               '            out += &format!("\n  +{:#x}: port {} original {}", base as usize + i * 4, f(a), f(b));',
               '        }',
               '    }',
               '    out',
               '}', '',
               'fn hex(s: &str) -> Vec<u8> {',
               '    (0..s.len() / 2).map(|i| u8::from_str_radix(&s[2 * i..2 * i + 2], 16).unwrap()).collect()',
               '}', '',
               'fn w(m: &mut mem::Mem, addr: u32, h: &str) {',
               '    m.write(addr, &hex(h));',
               '}', '',
               'fn patch(buf: &mut [u8], base: u32, diffs: &[(u32, &str)]) {',
               '    for (a, d) in diffs { let d = hex(d); let o = (*a - base) as usize; buf[o..o + d.len()].copy_from_slice(&d); }',
               '}', '', f'const CLOCK: u32 = {CLOCK_OBJ:#x};', '']
        for n, c in enumerate(self.cases):
            out.append('#[test]')
            out.append(f'fn case_{n}() {{')
            out.append('    let mut m = mem::Mem::new();')
            out.append(f'    globals::install_clock(&mut m, CLOCK, {c["time"]!r}, {c["dt"]!r});')
            for addr, data in c['writes']:
                out.append(f'    w(&mut m, {addr:#x}, "{bytes(data).hex()}");')
            if c['setup']:
                out.append('    ' + c['setup'])
            for k, (b, ln) in enumerate(c['watch']):
                out.append(f'    let before{k} = m.read({b:#x}, {ln});')
            if c['ret'] is not None and c['ret_int']:
                out.append(f'    let got = {c["rust"]};')
                out.append(f'    assert_eq!(got as u32, {int(c["ret"]) & 0xffffffff}u32, "returned value differs from the original");')
            elif c['ret'] is not None:
                out.append(f'    let got = {c["rust"]};')
                out.append(f'    assert!(close(got, {rs_f32(c["ret"])}), "returned {{got}}, original {rs_f32(c["ret"])}");')
            else:
                out.append(f'    {c["rust"]};')
            for k, (b, ln) in enumerate(c['watch']):
                mine = [(a, list(d)) for a, d in c['diffs'] if b <= a < b + ln]
                out.append(f'    let mut want{k} = before{k}.clone();')
                body = ', '.join(f'({a:#x}, "{bytes(d).hex()}")' for a, d in mine)
                out.append(f'    patch(&mut want{k}, {b:#x}, &[{body}]);')
                out.append(f'    assert!(mem_close(&m.read({b:#x}, {ln}), &want{k}), "memory at {b:#x} differs from the original:{{}}", report({b:#x}, &m.read({b:#x}, {ln}), &want{k}));')
            out.append('}')
            out.append('')
        path = os.path.join(TESTS, self.name + '.rs')
        open(path, 'w', encoding='utf-8').write('\n'.join(out))
        print('wrote', path, len(self.cases), 'cases')
