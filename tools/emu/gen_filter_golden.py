"""Generate crates/ht2-sim/tests/golden_filter.rs: the time filter run by the original code."""
import os
import random
import struct
import sys

sys.path.insert(0, os.path.dirname(__file__))
from emu import Emu, OBJ_BASE  # noqa: E402

OUT = os.path.join(os.path.dirname(__file__), '..', '..', 'crates', 'ht2-sim', 'tests', 'golden_filter.rs')
CLOCK_OBJ = OBJ_BASE + 0x100000
THIS = OBJ_BASE
WEIGHTS = {'WEIGHT_STEP': 0x4eaa0e, 'WEIGHT_LINEAR': 0x4eaa41, 'WEIGHT_QUADRATIC': 0x4eaa77, 'WEIGHT_COSINE': 0x4eab02}
rnd = random.Random(99)


def f32(x):
    return struct.unpack('<f', struct.pack('<f', x))[0]


def rs(x):
    return repr(f32(x)) + 'f32'


lines = ['// Generated by tools/emu/gen_filter_golden.py from the original code; do not edit.',
         'use ht2_sim::filter::*;', 'use ht2_sim::globals;', 'use ht2_sim::mem::Mem;', '',
         'const CLOCK: u32 = 0x2a10_0000;', 'const THIS: u32 = 0x2a00_0000;', '',
         'fn close(got: f32, want: f32) -> bool {', '    (got - want).abs() <= 1e-4 * want.abs().max(1.0)', '}', '']

for n in range(12):
    wname = rnd.choice(list(WEIGHTS))
    mixname = rnd.choice([None, None, 'WEIGHT_LINEAR', 'WEIGHT_COSINE'])
    window = rnd.choice([0.2, 0.3, 0.5, 0.75, 1.0])
    default = rnd.choice([0.0, 0.5, 2.0])
    e = Emu()
    e.install_crt_hooks()
    e.set_u32(0x6974c4, CLOCK_OBJ)
    t = rnd.uniform(0, 20)
    e.write(CLOCK_OBJ + 0xb98, struct.pack('<d', t))
    e.write(CLOCK_OBJ + 0xb90, struct.pack('<d', 0.0))
    body = [f'    let mut m = Mem::new();', f'    globals::install_clock(&mut m, CLOCK, {t!r}, 0.0);',
            f'    new(&mut m, THIS, {wname}, {rs(window)}, {mixname or 0}, {rs(default)});']
    e.call(0x4eab58, [WEIGHTS[wname], window, WEIGHTS[mixname] if mixname else 0, default], 'ifif', this=THIS)
    for step in range(rnd.randint(15, 60)):
        t += rnd.uniform(0.0, 0.09) if rnd.random() < 0.9 else 0.0   # sometimes the same instant
        e.write(CLOCK_OBJ + 0xb98, struct.pack('<d', t))
        body.append(f'    globals::set_time(&mut m, {t!r});')
        if rnd.random() < 0.7:
            v = rnd.uniform(-5, 20)
            e.call(0x4eacce, [v, 0], 'fi', this=THIS)
            body.append(f'    add(&mut m, THIS, {rs(v)});')
        got = e.call(0x4eaf98, [], '', this=THIS)
        body.append(f'    assert!(close(value(&m, THIS), {rs(got)}), "value after step {step}");')
    # final state: the object and both sample arrays
    obj = e.read(THIS, 0x20)
    nsamples = struct.unpack_from('<i', obj, 0x1c)[0]
    times_p, values_p = struct.unpack_from('<II', obj, 8)
    body.append(f'    assert_eq!(m.read(THIS, 0x20), {list(obj)!r});')
    body.append(f'    assert_eq!(m.read({times_p:#x}, {nsamples * 4}), {list(e.read(times_p, nsamples * 4))!r});')
    body.append(f'    assert_eq!(m.read({values_p:#x}, {nsamples * 4}), {list(e.read(values_p, nsamples * 4))!r});')
    lines += [f'#[test]', f'fn filter_scenario_{n}_{wname.lower()}() {{'] + body + ['}', '']

open(OUT, 'w', encoding='utf-8').write('\n'.join(lines))
print('wrote', OUT)
