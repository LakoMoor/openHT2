"""Golden test for the curve segments of the roads: the arc-length polynomial the original builds
for a piece (0x48dbb0: speed interpolated at Chebyshev nodes, integrated)."""
import os
import random
import struct
import sys

import pefile

sys.path.insert(0, os.path.dirname(__file__))
from harness import Harness, TESTS  # noqa: E402
from emu import OBJ_BASE, STUB, EXE  # noqa: E402

h = Harness('golden_road', [])
e = h.e


def alloc(emu):
    n = emu.arg(0)
    a = emu.heap_next
    emu.heap_next += (n + 15) & ~15
    return a


e.hook_ret(0x44b740, alloc)                # pooled allocator of the C++ containers
e.hook_ret(0x44b4a0, lambda emu: 0)        # and its release
e.hook_ret(0x61d1c8, lambda emu: 0)        # free
e.hook_ret(0x50d190, lambda emu: 0)
e.write(STUB + 0x200, bytes([0xc2, 0x04, 0x00]))
e.write(STUB + 0x210, bytes.fromhex('8b4424048b4c2408870889c8c20800'))  # InterlockedExchange
for imp in pefile.PE(EXE).DIRECTORY_ENTRY_IMPORT:
    for i in imp.imports:
        if i.name and b'CriticalSection' in i.name:
            e.write(i.address, struct.pack('<I', STUB + 0x200))
        if i.name == b'InterlockedExchange':
            e.write(i.address, struct.pack('<I', STUB + 0x210))
SRC, PIECE = OBJ_BASE + 0x1000, OBJ_BASE + 0x2000
r = random.Random(7)
out = ['// Generated by tools/emu/gen_road_golden.py from the original code; do not edit.',
       'use ht2_sim::road::Segment;', '']
for k in range(40):
    scale = r.choice([5, 50, 300])
    p0 = [r.uniform(-1000, 1000), r.uniform(-1000, 1000), r.uniform(0, 50)]
    pts = [p0] + [[p0[0] + r.uniform(-scale, scale), p0[1] + r.uniform(-scale, scale), p0[2] + r.uniform(-3, 3)] for _ in range(3)]
    p0, p1, p2, p3 = pts
    A = [-p0[i] + 3 * p1[i] - 3 * p2[i] + p3[i] for i in range(3)]
    B = [3 * p0[i] - 6 * p1[i] + 3 * p2[i] for i in range(3)]
    C = [-3 * p0[i] + 3 * p1[i] for i in range(3)]
    src = bytearray(0x244)
    for j, v in enumerate([A, B, C, p0]):
        src[24 * j:24 * j + 24] = struct.pack('<3d', *v)
    struct.pack_into('<I', src, 0x240, 4)
    h.reset()
    e.write(SRC, bytes(src))
    e.call(0x48dbb0, [SRC], 'i', this=PIECE, max_insn=50_000_000)
    n = struct.unpack('<I', e.read(PIECE + 0x630, 4))[0]
    arc = struct.unpack('<%dd' % n, e.read(PIECE + 0x570, 8 * n))
    # movement along the piece (0x48df80): t, distance and parameter step by reference
    moves = []
    for _ in range(4):
        t0, d0 = r.random(), r.choice([1, -1]) * r.uniform(0.1, 2 * scale)
        V = OBJ_BASE + 0x9000
        e.write(V, struct.pack('<3d', t0, d0, 0.1))
        ret = e.call(0x48df80, [V, V + 8, V + 16], 'iii', this=PIECE)
        res = e.eax
        t1, d1, s1 = struct.unpack('<3d', e.read(V, 24))
        moves.append((t0, d0, t1, d1, s1, res))
    out += ['#[test]', f'fn case_{k}() {{',
            f'    let p = [{", ".join("[" + ", ".join(repr(x) for x in q) + "]" for q in pts)}];',
            '    let s = Segment::new(1, 0.0, 1, [8.0, 8.0], &p).unwrap();',
            '    let got = s.arc_poly().unwrap();',
            f'    let want = [{", ".join(repr(x) for x in arc)}];',
            '    assert_eq!(got.len(), want.len());',
            '    let len = |c: &[f64]| c.iter().sum::<f64>();',
            '    assert!((len(got) - len(&want)).abs() <= 1e-9 * len(&want).abs().max(1.0), "length {} vs {}", len(got), len(&want));',
            '    for t in [0.1, 0.37, 0.5, 0.81, 1.0] {',
            '        let ev = |c: &[f64]| c.iter().fold(0.0, |r, k| r * t + k);',
            '        assert!((ev(got) - ev(&want)).abs() <= 1e-9 * ev(&want).abs().max(1.0), "t={t}: {} vs {}", ev(got), ev(&want));',
            '    }']
    for t0, d0, t1, d1, s1, res in moves:
        out += ['    {', f'        let (mut t, mut d, mut k, mut step) = ({t0!r}, {d0!r}, 0usize, 0.1);',
                '        let end = s.advance(&mut t, &mut d, &mut k, &mut step);',
                f'        assert_eq!(end, {"true" if res else "false"});',
                # the original's six secant steps can wander far before they settle, so the last
                # digits of the arc polynomial (x87 against f64) show up in t
                f'        assert!((t - {t1!r}).abs() <= 1e-4 && (d - {d1!r}).abs() <= 1e-9 * {abs(d1)!r}f64.max(1.0), "t {{t}} d {{d}}");',
                '    }']
    out += ['}', '']
open(os.path.join(TESTS, 'golden_road.rs'), 'w', encoding='utf-8').write('\n'.join(out))
print('wrote golden_road.rs')
