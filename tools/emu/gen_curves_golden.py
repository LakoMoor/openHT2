"""Generate crates/ht2-sim/tests/golden_curves.rs from the original code running in the emulator.

Needs the game (HT2_GAME or the default path in emu.py), pefile, unicorn.
    python tools/emu/gen_curves_golden.py
"""
import os
import random
import struct
import sys

sys.path.insert(0, os.path.dirname(__file__))
from emu import Emu, TECH_BASE, SCRATCH  # noqa: E402

OUT = os.path.join(os.path.dirname(__file__), '..', '..', 'crates', 'ht2-sim', 'tests', 'golden_curves.rs')
e = Emu()
e.load_tech()
rnd = random.Random(1234)
IDS = [0, 5, 8, 18, 19, 21, 25, 31, 33, 38]


def rec_fields(i):
    b = e.read(TECH_BASE + i * 0x970, 0x970)
    f = lambda o: struct.unpack_from('<f', b, o)[0]
    return dict(radius=f(100), num_gears=struct.unpack_from('<i', b, 144)[0], air_press=f(172), air_resist=f(176),
                max_torque=f(192), axle=f(204), gears=[f(208 + 4 * g) for g in range(15)], tach=f(268))


def fl(x):
    return repr(float(struct.unpack('<f', struct.pack('<f', x))[0])) + 'f32' if x == x else 'f32::NAN'


def num(x):
    return fl(x)


lines = []
emit = lines.append
emit('// Generated by tools/emu/gen_curves_golden.py from the original code; do not edit.')
emit('use ht2_sim::curves::*;')
emit('use ht2_sim::TechRec;')
emit('')
emit('struct R { radius: f32, num_gears: i32, air_press: f32, air_resist: f32, max_torque: f32, axle: f32, gears: [f32; 15], tach: f32 }')
emit('impl R {')
emit('    fn bytes(&self) -> Vec<u8> {')
emit('        let mut b = vec![0u8; 0x970];')
emit('        let mut put = |o: usize, v: f32| b[o..o + 4].copy_from_slice(&v.to_le_bytes());')
emit('        put(100, self.radius); put(172, self.air_press); put(176, self.air_resist);')
emit('        put(192, self.max_torque); put(204, self.axle); put(268, self.tach);')
emit('        for (g, v) in self.gears.iter().enumerate() { put(208 + 4 * g, *v); }')
emit('        b[144..148].copy_from_slice(&self.num_gears.to_le_bytes());')
emit('        b')
emit('    }')
emit('}')
emit('')
emit('fn close(got: f32, want: f32) -> bool {')
emit('    (got - want).abs() <= 1e-4 * want.abs().max(1.0)')
emit('}')
emit('')
emit('const RECS: &[R] = &[')
for i in IDS:
    r = rec_fields(i)
    emit(f"    R {{ radius: {num(r['radius'])}, num_gears: {r['num_gears']}, air_press: {num(r['air_press'])}, air_resist: {num(r['air_resist'])}, max_torque: {num(r['max_torque'])}, axle: {num(r['axle'])}, gears: [{', '.join(num(g) for g in r['gears'])}], tach: {num(r['tach'])} }},")
emit('];')
emit('')

# --- pure functions ---------------------------------------------------
cases = []
for _ in range(40):
    x, y = rnd.uniform(0.01, 40), rnd.uniform(0.0, 5)
    cases.append(('00507330', f'fn_00507330({num(x)}, {num(y)})', e.call(0x507330, [x, y], 'ff')))
for _ in range(40):
    a, b, c, d = rnd.uniform(0, 30), rnd.uniform(0, 5), rnd.uniform(0, 5), rnd.uniform(0, 50)
    cases.append(('00507360', f'fn_00507360({num(a)}, {num(b)}, {num(c)}, {num(d)})', e.call(0x507360, [a, b, c, d], 'ffff')))
for _ in range(80):
    peak = rnd.uniform(50, 400)
    rpm = rnd.uniform(0, 3.5 * peak)
    tq, sc = rnd.uniform(100, 2000), rnd.uniform(0.5, 3)
    cases.append(('00507380', f'fn_00507380({num(rpm)}, {num(peak)}, {num(tq)}, {num(sc)})', e.call(0x507380, [rpm, peak, tq, sc], 'ffff')))
for _ in range(30):
    a, b, t = rnd.uniform(-5, 5), rnd.uniform(-5, 5), rnd.uniform(-0.7, 1.7)
    cases.append(('00507440', f'fn_00507440({num(a)}, {num(b)}, {num(t)})', e.call(0x507440, [0, a, b, t], 'ifff')))
emit('#[test]')
emit('fn pure_functions_match_the_original() {')
for name, expr, want in cases:
    emit(f'    assert!(close({expr}, {num(want)}), "{name} {expr.replace(chr(34), chr(39))}");')
emit('}')
emit('')

# --- functions that read the tech record -------------------------------
emit('#[test]')
emit('fn record_functions_match_the_original() {')
emit('    let bytes: Vec<Vec<u8>> = RECS.iter().map(R::bytes).collect();')
for k, i in enumerate(IDS):
    emit(f'    let r{k} = TechRec::new(&bytes[{k}]);')
for k, i in enumerate(IDS):
    ng = rec_fields(i)['num_gears']
    for _ in range(6):
        x, y, g = rnd.uniform(0, 3000), rnd.uniform(0, 2), rnd.randint(0, 14)
        v = e.call(0x507490, [i, x, g], 'ifi')
        emit(f'    assert!(close(fn_00507490(r{k}, {num(x)}, {g}), {num(v)}), "507490 rec {i}");')
    for _ in range(10):
        x, y = rnd.uniform(0, 45), rnd.uniform(0, 2)
        v = e.call(0x5074d0, [i, x, y], 'iff')
        emit(f'    assert!(close(fn_005074d0(r{k}, {num(x)}, {num(y)}), {num(v)}), "5074d0 rec {i}");')
    for g in range(0, 15):
        y = rnd.uniform(0, 2)
        outp = SCRATCH + 0x100
        e.write(outp, b'\0\0\0\0')
        v = e.call(0x507550, [i, g, y, outp], 'iifi')
        out = e.f32(outp)
        emit(f'    {{ let (v, o) = fn_00507550(r{k}, {g}, {num(y)}); assert!(close(v, {num(v)}) && close(o, {num(out)}), "507550 rec {i} gear {g}: {{v}} {{o}}"); }}')
    for _ in range(3):
        y = rnd.uniform(0, 2)
        pg, po = SCRATCH + 0x100, SCRATCH + 0x104
        e.write(pg, b'\0' * 8)
        v = e.call(0x507710, [i, y, pg, po], 'ifii')
        g = struct.unpack('<i', e.read(pg, 4))[0]
        o = struct.unpack('<i', e.read(po, 4))[0]  # the original stores an int-typed slot
        of = e.f32(po)
        emit(f'    {{ let (v, g, o) = fn_00507710(r{k}, {num(y)}); assert!(close(v, {num(v)}) && g == {g} && close(o, {num(of)}), "507710 rec {i}: {{v}} {{g}} {{o}}"); }}')
emit('}')

open(OUT, 'w', encoding='utf-8').write('\n'.join(lines) + '\n')
print('wrote', OUT, len(cases), 'pure cases')
